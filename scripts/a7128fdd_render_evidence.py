"""Session arena-a7128fdd — render the Markdown siblings from their JSON records.

``scripts/build.py::load_direct_observations`` refuses a record whose ``.md``
sibling is missing, so the prose and the numbers cannot drift apart. This makes
that guarantee real rather than aspirational: the Markdown is *generated* from
the JSON, so it can be re-derived and diffed at any time.

Run it after editing either JSON record:

    python -m scripts.a7128fdd_render_evidence

It writes nothing else and changes no value. If the generated file already
matches what is committed, it says so and exits 0 — which is what makes
``--check`` usable in CI.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "data" / "research" / "a7128fdd"

