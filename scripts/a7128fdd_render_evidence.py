def render_verification(rec: dict) -> str:
    c = rec["conclusions"]
    snap = rec["published_snapshot_verified"]
    inv = rec["inventory_verified"]
    L = [
        "# Line-by-line verification of the published snapshot (arena-a7128fdd)",
        "",
        "> Generated from `verification.json` by `python -m scripts.a7128fdd_render_evidence`.",
        "",
        f"Verified **{rec['verified_at']}**. Every arithmetic result below is re-derivable from the linked "
        "source with the repository's own de-vig rule.",
        "",
        "## 1. The published page and the downloadable snapshot are one observation",
        "",
        f"- Live root `data/latest.json` `generated_at`: `{snap['live_root_data_latest_json_generated_at']}`",
        f"- Live root page stamp: `{snap['live_root_page_snapshot_generated']}`",
        f"- Agree: **{snap['agree']}**",
        "",
        snap["note"],
        "",
        "Sources: " + " · ".join(f"<{u}>" for u in snap["source_urls"]),
        "",
        "## 2. The published inventory count equals what the source API returned",
        "",
        f"- Read `{inv['hotspawn_api']}` directly at {inv['read_at']}: **{inv['records_returned']}** records",
        f"- Published counts: inventory **{inv['published_counts']['inventory']}**, upcoming "
        f"**{inv['published_counts']['upcoming']}**",
        f"- Agree: **{inv['agree']}**",
        "",
        inv["note"],
        "",
        "## 3. Published probabilities re-derived from independent surfaces",
        "",
        rec["method"],
        "",
        "| Hotspawn id | Fixture | Published | Independent source | Odds as published | Re-derived | Exact |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for r in rec["rows"]:
        odds = " / ".join(f"{k} {v}" for k, v in r["odds_as_published"].items())
        al = r["devigged_aligned_to_hotspawn"]
        re_derived = "—" if al[0] is None else f"{al[0]:.4f} / {al[1]:.4f}"
        pub = f"{r['published_probabilities'][0]:.4f} / {r['published_probabilities'][1]:.4f}"
        # Computed outside the f-string: Python 3.11 forbids backslashes and
        # nested same-quote f-strings inside an f-string expression.
        exact_cell = "**yes**" if r["exact_match"] else f"no (delta {r['abs_delta_side_a']})"
        L.append(f"| {r['hotspawn_id']} | {' vs '.join(r['teams'])} | {pub} ({r['published_method']}) "
                 f"| [{r['independent_source']}]({r['source_url']}) | {odds} | {re_derived} "
                 f"| {exact_cell} |")
    L += [
        "",
        f"- Rows checked: **{c['rows_checked']}**",
        f"- Exact four-decimal reproductions: **{c['exact_reproductions']}**",
        f"- Directionally agreeing but from a different surface: **{c['close_but_different_source']}**",
        f"- Name bindings left unresolved: **{c['name_bindings_unresolved']}**",
        f"- Published values changed by this verification: **{c['published_values_changed']}**",
        "",
        c["reading"],
        "",
    ]
    return "\n".join(L)


def _label(path: Path) -> str:
    """Repo-relative when possible, absolute otherwise (tests use temp dirs)."""
    try:
        return str(path.relative_to(ROOT))
    except ValueError:
        return str(path)


def write(path: Path, text: str, check: bool) -> bool:
    existing = path.read_text(encoding="utf-8") if path.exists() else None
    if existing == text:
        print(f"unchanged: {_label(path)}")
        return True
    if check:
        print(f"DRIFT: {_label(path)} does not match its JSON record", file=sys.stderr)
        return False
    path.write_text(text, encoding="utf-8")
    print(f"wrote {_label(path)} ({len(text.encode('utf-8'))} bytes)")
    return True


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true",
                    help="fail instead of writing if a Markdown sibling has drifted from its JSON")
    args = ap.parse_args(argv)

    ok = True
    obs = json.loads((OUT / "direct-observations.json").read_text(encoding="utf-8"))
    ok &= write(OUT / "direct-observations.md", render_observations(obs), args.check)
    ver = json.loads((OUT / "verification.json").read_text(encoding="utf-8"))
    ok &= write(OUT / "verification.md", render_verification(ver), args.check)
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
